package com.abatalev.demo.etcdhikari.provisor.etcd;

import java.util.ArrayList;
import java.util.List;

/**
 * Сколько соединений флота можно отдать инстансам прямо сейчас.
 *
 * <p>Сумма долей сервиса всегда равна N, и сумма приказанных потолков никогда не превышает N.
 * Потолок бюджета, тем не менее, пробивается на каждом переходе, где одновременно есть рост и
 * сжатие: сжатому инстансу приказали меньше, но он ещё держит соединения — освобождённое место
 * ещё не освободилось. Приказ освободить нельзя, а выдать освобождаемое другому — значит превысить
 * N на всё время дренажа.
 *
 * <p>Исходная точка — не потолки, а то, что инстансы действительно держат:
 *
 * <pre>
 *   занято_i = потолок_i + долг_i
 *   рост     = N − сумма занято
 * </pre>
 *
 * <p>Потолки одни показывают место преждевременно: сжатому инстансу приказали меньше, но он ещё
 * держит соединения, и место под нового инстанса ещё не освободилось. Долг берётся из публикации
 * инстанса: сколько соединений он держит сверх своего потолка. Если публикации нет или она
 * относится к прежнему потолку (инстанс ещё не видел текущую команду), берётся худший случай —
 * инстанс держит всё, что мог держать, то есть свой потолок. Худший случай тут безопасен именно
 * потому, что долг входит в сумму с плюсом: завышенная оценка лишь придержит рост флота, а не
 * позволит превысить бюджет.
 *
 * <p>Между проходами место не «резервируется» и не планируется: рост пересчитывается на каждой
 * публикации, поэтому место освобождается ровно тогда, когда инстанс его действительно отпустил.
 * Никакого ожидания в провижёре нет — освобождение приходит публикацией и само зовёт пересчёт.
 * Обратная сторона: пока место не освободилось, флот работает меньше бюджета, и это осознанный
 * размен превышения на недопровиживание.
 *
 * <p>Чистая функция: ни клиента, ни потоков, ни часов — только числа и ключи, поэтому правило
 * покрывается тестами без etcd. Повторный вызов на одном и том же снимке даёт тот же результат, а
 * значит две реплики провизёра в окне перехвата лидерства не разойдутся.
 */
public final class ConnectionGrowth {

    /**
     * Состояние узла на момент снимка.
     *
     * @param nodeKey полный ключ узла регистрации
     * @param ceiling текущее значение {@code maximumPoolSize}; 0, если ключа нет
     * @param target доля по распределению; {@code null} — доли нет, конфигурация снимается
     * @param reported опубликованное неосвобождённое сжатие; {@code null} — публикации нет
     * @param reportAcknowledged публикация относится к текущему потолку (инстанс её видел)
     */
    public record NodeState(String nodeKey, int ceiling, Integer target, Integer reported,
            boolean reportAcknowledged) {

        /** Узлу не полагается доля: конфигурация снимается целиком, потолок становится нулём. */
        public boolean losesConfig() {
            return target == null;
        }
    }

    /**
     * Решение по одному узлу.
     *
     * @param nodeKey полный ключ узла регистрации
     * @param command потолок, который надо записать; 0 — долю выдать нечем, узел не обслуживается
     * @param target доля по распределению: сколько узлу положено, независимо от свободного места
     * @param grows ли это рост относительно текущего потолка
     * @param shrinks ли это сжатие относительно текущего потолка
     */
    public record Decision(String nodeKey, int command, int target, boolean grows, boolean shrinks) {

        /** Нулевая команда не пишется: ноль сервис отклоняет, а узел без доли не обслуживается. */
        public boolean servable() {
            return command > 0;
        }
    }

    /**
     * Результат планирования роста.
     *
     * @param decisions решения по узлам, у которых доля полагается (в порядке переданных ключей)
     * @param losesConfig узлы без доли: их конфигурация снимается, ключ записи не пишется
     * @param growable величина роста, общая на сервис: сколько флот реально не занимает
     * @param sumCeilings сумма текущих потолков
     * @param sumDebt сумма долгов по худшему случаю — ею ограничивается рост
     * @param sumConfirmedDebt сумма долгов по подтверждённым публикациям — что флот действительно
     *         держит сверх потолков
     * @param sumHeld сумма «потолок + долг» — сколько флот занимает по факту
     */
    public record Result(List<Decision> decisions, List<String> losesConfig, int growable,
            int sumCeilings, int sumDebt, int sumConfirmedDebt, int sumHeld) {
    }

    private ConnectionGrowth() {
    }

    /**
     * Планирует рост по снимку сервиса.
     *
     * @param budget бюджет активного флота N
     * @param nodes состояние всех живых узлов сервиса
     */
    public static Result plan(int budget, List<NodeState> nodes) {
        long sumCeilings = 0;
        long sumDebt = 0;
        long sumConfirmedDebt = 0;
        long sumHeld = 0;
        for (NodeState node : nodes) {
            sumCeilings += node.ceiling();
            sumDebt += debt(node);
            // Отдельно то, что подтверждено публикацией: худший случай для ограничения роста
            // безопасен, но как наблюдение он был бы выдумкой — на штатном перезапуске флота, где
            // публикаций нет ни у кого, он даёт N целиком.
            sumConfirmedDebt += confirmedDebt(node);
            sumHeld += node.ceiling() + debt(node);
        }

        // Свободно ровно то, что флот не занимает. Потолки считать нельзя: место сжимаемого
        // инстанса освободится только когда он его действительно отпустит.
        int growable = (int) Math.max(0, budget - sumHeld);

        List<Decision> decisions = new ArrayList<>();
        List<String> losesConfig = new ArrayList<>();
        // Свободное место общее на сервис, поэтому раздаётся по одному, а не каждому целиком:
        // иначе два растущих инстанса получают каждое по всей сумме и флот занимает
        // N + free×(число растущих). Порядок раздачи — порядок переданных ключей, тот же, что и
        // у долей, поэтому повторный расчёт на одном снимке даёт тот же результат.
        int free = growable;
        for (NodeState node : nodes) {
            if (node.losesConfig()) {
                losesConfig.add(node.nodeKey());
                continue;
            }
            int command = Math.min(node.target(), node.ceiling() + free);
            free -= Math.max(0, command - node.ceiling());
            decisions.add(new Decision(node.nodeKey(), command, node.target(),
                    command > node.ceiling(), command < node.ceiling()));
        }
        return new Result(decisions, losesConfig, growable, (int) sumCeilings, (int) sumDebt,
                (int) sumConfirmedDebt, (int) sumHeld);
    }

    /**
     * Долг одного узла: неосвобождённое сжатие по публикации инстанса.
     *
     * <p>Публикация, относящаяся к прежнему потолку, для текущей бесполезна: инстанс писал её,
     * когда держал другое число соединений. Пока новая команда не подтверждена публикацией, берём
     * худший случай — инстанс держит всё, что мог, то есть свой потолок.
     *
     * @return сколько узел держит сверх потолка; неотрицателен по построению
     */
    public static int debt(NodeState node) {
        if (node.reported() != null && node.reportAcknowledged()) {
            return Math.max(0, node.reported());
        }
        return Math.max(0, node.ceiling());
    }

    /**
     * Неосвобождённое сжатие по подтверждённой публикации: сколько узел действительно держит
     * сверх потолка.
     *
     * <p>В отличие от {@link #debt(NodeState)} без подтверждения это ноль, а не потолок: держать
     * сверх потолка без публикации нельзя — инстанс либо ничего сверху не держит, либо сообщил бы
     * об этом. Публикация приходит только при изменении, поэтому у только что пересозданного пула
     * её нет, и это норма, а не зависшее сжатие.
     */
    public static int confirmedDebt(NodeState node) {
        if (node.reported() != null && node.reportAcknowledged()) {
            return Math.max(0, node.reported());
        }
        return 0;
    }
}
