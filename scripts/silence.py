#!/usr/bin/env python3
"""Правила молчания инстанса из живого состава (prometheus/rules/instances.yml и .test.yml).

Аргументы (оба обязательны):
  1) путь файла правил, который нужно записать
  2) путь файла теста правил, который нужно записать

Состав берётся из `docker compose ps` (scripts/fleet.py), а не из перечня в конфигурации:
число реплик группы задаётся `--scale`, и единственный источник развёрнутого состава —
сам compose. Список включает и остановленные контейнеры: правило absent() обязано жить
и для упавшего инстанса, иначе остановка выглядела бы как «инстанса больше нет», а не
как «инстанс молчит».

Зачем это вместо списка целей сбора: приложения отправляют метрики в единую точку приёма,
и сборщик опрашивает только её. Список инстансов в целях сборщика был второй копией
`.env`, которая молча разъезжалась с ним. Теперь отсутствие ряда объявляет правило,
а список инстансов остаётся в одном месте — в развёрнутом составе.

Ряд, по которому судит молчание, — состояние пула: у процесса он есть всегда, независимо
от того, есть ли конфигурация. Это важно: инстанс без доли бюджета честно не обслуживает
трафик (503, готовность DOWN), но в наблюдении он обязан оставаться виден — иначе
регулярное состояние флота было бы неотличимо от упавшего процесса.

Файлы зафиксированы в репозитории, чтобы сборщик поднимался даже без запуска make;
расхождение с составом ловит `make check-silence`, а `make up` перегенерирует файлы и
перезагружает правила (SIGHUP) после старта контейнеров.
"""

import os
import sys

from fleet import fleet

MARKER = "pool_config_state"

RULES_HEADER = f"""# ПРАВИЛА МОЛЧАНИЯ ИНСТАНСА. Файлы генерируются: scripts/silence.py из живого состава
# `docker compose ps` (`make silence-rules`), сверка — `make check-silence`. Состав меняется
# числом реплик группы (`--scale`), поэтому перечень контейнеров берётся из compose, а не из
# конфигурации стенда.
#
# Пока инстансы отдавали метрики по /actuator/prometheus, сборщик опрашивал каждый отдельно, и
# молчание процесса означало молчание цели. Теперь метрики идут отправкой в одну точку приёма,
# и одна цель на весь флот молчит иначе, чем молчит один инстанс: список целей такую
# неотличимость больше не выражает. Отсюда правила ниже — отсутствие ряда поимённо.
#
# Ряд состояния пула выбран потому, что существует у процесса всегда, независимо от наличия
# конфигурации: снятие конфигурации его не убирает. Поэтому инстанс без доли бюджета (503,
# готовность DOWN) молчанием не считается, а упавший процесс считается.
#
# Молчание снимается само собой: как только ряд появился, absent() перестаёт срабатывать.
#
# Окно `for` — 2м, и столько же нужно на обнаружение. Измерено на стенде (остановка контейнера
# инстанса, штатное время): от остановки до срабатывания прошло 160с. Раскладывается так — дверь
# убирает ряд из своей выдачи через metric_expiration (30с), сборщик на следующем опросе помечает
# его устаревшим, и только тогда absent() начинает видеть отсутствие; плюс окно for 2м и шаг
# проверки правил. Пятиминутное окно lookback здесь не участвует: устаревший ряд сборщик не
# переносит вперёд, а метка устаревания действует сразу. Lookback вступает в дело только если
# дверь продолжает отдавать ряд без свежих точек: тогда отсутствие заметят лишь через окно
# lookback, и до срабатывания пройдёт около 7 минут. Поэтому в наборе проверок правил нарушение
# задано восьмиминутным промежутком без точек, а норма — точками не старше минуты.
#
# Запас берётся в сторону ложного молчания, а не ложной тревоги: молчание — не «инстанс сейчас
# упал», а «инстанса нет в наблюдении дольше, чем мы обычно ждём доставку». Промежуток на
# возврат ряда: измерено 20с от старта процесса до снятия правила (метрики приходят раз в 5с),
# то есть короткий обрыв доставки — десятки секунд — правилом молчания не ловится.

groups:
  - name: instances
    rules:
"""


def rule(service: str, group: str, instance: str) -> str:
    # Метка node в правиле обязательна: promtool считает правила одинаковыми по имени и набору
    # меток, а правила молчания отличаются только выражением. Без неё check rules падает на
    # «duplicate rules», и проверка правил перестаёт быть проверкой. Значение совпадает с тем,
    # что absent() и так проставляет в метке node, — метка задана явно, чтобы правило называло
    # инстанс само по себе и переживало правку выражения.
    return f"""      - alert: InstanceSilent
        expr: absent({MARKER}{{node="{instance}"}})
        for: 2m
        labels:
          severity: warning
          node: {instance}
        annotations:
          summary: "Инстанс {{{{ $labels.node }}}} молчит в наблюдении"
          description: >-
            {service}/{group}/{instance}: нет ряда {MARKER} — процесс не присылает метрики либо
            отправка в точку приёма не доходит. Состав стенда: make check-instances.
"""


TEST_HEADER = """# Проверка правил молчания инстанса: правило обязано молчать, когда ряды есть, срабатывать,
# когда инстанса нет в рядах, и сниматься само, когда ряд вернулся. Проверяется в составе
# make test, поэтому «правило молчит всегда» — тоже падение проверки, а не тихая дырка
# в наблюдении.
#
# Файл генерируется вместе с правилами (scripts/silence.py, make silence-rules): тест обязан
# покрывать ровно текущий состав, иначе удаление инстанса из состава молча убрало бы и его
# правило из-под проверки.
#
# Ряд состояния пула берётся по одному на инстанс: настоящий ряд помечен state, и absent()
# смотрит на отсутствие любого из них, поэтому одного ряда на инстанс достаточно.
#
# Границу ожидания (for: 2m) проверяем не точно: шаг evaluation_interval здесь минутный, а
# в сборщике 5с, поэтому фиксируем заведомо не наступившее и заведомо наступившее состояния.
#
# Здесь промежуток без точек задан восьмью минутами, и это худший случай, а не обычный. В
# сборщике ряд, пропавший из выдачи двери, помечается устаревшим на следующем опросе и
# отсутствием становится сразу (на стенде от остановки инстанса до срабатывания прошло 160с:
# 30с, пока дверь держит ряд после последней точки, плюс for 2м, плюс шаг проверки). Здесь же
# проверка правил не знает про устаревание: у неё пропавший ряд остаётся живым ещё 5 минут
# (окно lookback), поэтому восемь минут покрывают худший случай — когда дверь продолжает
# отдавать ряд без свежих точек. Наборы проверяют правило, а не скорость обнаружения:
# скорость измерена на стенде (docs/operations.md).
rule_files:
  - instances.yml
evaluation_interval: 1m
tests:
"""


def series_of(instance: str, values: str) -> str:
    return f"      - series: '{MARKER}{{node=\"{instance}\",state=\"applied\"}}'\n        values: '{values}'\n"


def alert_block(instance: str, service: str, group: str) -> str:
    return f"""          - exp_labels:
              severity: warning
              node: {instance}
            exp_annotations:
              summary: Инстанс {instance} молчит в наблюдении
              description: >-
                {service}/{group}/{instance}: нет ряда {MARKER} — процесс не присылает метрики либо
                отправка в точку приёма не доходит. Состав стенда: make check-instances.
"""


def test_file(instances):
    parts = [TEST_HEADER]

    # 1. Все ряды на месте — молчания нет.
    parts.append('  - name: "у всех инстансов есть ряды: молчания нет"\n    interval: 1m\n'
                 "    input_series:\n")
    for _service, _group, instance in instances:
        parts.append(series_of(instance, "1x10"))
    parts.append("    alert_rule_test:\n"
                 "      - eval_time: 9m\n        alertname: InstanceSilent\n        exp_alerts: []\n\n")

    # 2. У последнего инстанса рядов нет — срабатывает именно он.
    last = instances[-1]
    parts.append('  - name: "у одного инстанса рядов нет: срабатывает именно он"\n'
                 "    interval: 1m\n    input_series:\n")
    for service, group, instance in instances[:-1]:
        parts.append(series_of(instance, "1x10"))
    parts.append(f"      # {last[0]}/{last[1]}/{last[2]} отправить ничего не смог: процесса нет\n"
                 "      # или отправка не доходит.\n")
    parts.append("    alert_rule_test:\n"
                 "      - eval_time: 1m\n        alertname: InstanceSilent\n        exp_alerts: []\n"
                 "      - eval_time: 3m\n        alertname: InstanceSilent\n        exp_alerts:\n")
    parts.append(alert_block(last[2], last[0], last[1]))
    parts.append("\n")

    # 3. Ряд пропал и вернулся — молчание снимается само. Второй инстанс: у него ряд
    #    пропадает, у остальных — на месте, чтобы правило сработало только на нём.
    if len(instances) >= 2:
        lost = instances[1]
        parts.append('  - name: "ряд пропал и вернулся: молчание снимается само"\n'
                     "    interval: 1m\n    input_series:\n")
        for service, group, instance in instances:
            if instance == lost[2]:
                # Пропадает на 8 минут (у проверки правил окно lookback — 5 минут), потом
                # возвращается: как у процесса, который надолго перестал присылать метрики
                # и снова заработал.
                parts.append(series_of(instance, "1x3 _x8 1x3"))
            else:
                parts.append(series_of(instance, "1x10"))
        parts.append("    alert_rule_test:\n"
                     "      # Ряд последний раз приходил на 3-й минуте: до 8-й он ещё «жив»\n"
                     "      # (lookback 5м), после — отсутствует. Окно for в 2м отсчитывается\n"
                     "      # от 8-й, то есть срабатывание ожидается к 10-й.\n"
                     "      - eval_time: 7m\n        alertname: InstanceSilent\n        exp_alerts: []\n"
                     "      - eval_time: 9m\n        alertname: InstanceSilent\n        exp_alerts: []\n"
                     "      - eval_time: 11m\n        alertname: InstanceSilent\n        exp_alerts:\n")
        parts.append(alert_block(lost[2], lost[0], lost[1]))
        parts.append("      # Ряд вернулся на 12-й минуте: молчание снято само, без вмешательства.\n"
                     "      - eval_time: 13m\n        alertname: InstanceSilent\n        exp_alerts: []\n")

    return "".join(parts)


def main():
    if len(sys.argv) < 3:
        print("usage: silence.py <rules-file> <test-file>", file=sys.stderr)
        return 2
    rules_file, test_file_path = sys.argv[1], sys.argv[2]

    instances = fleet()
    if not instances:
        print("состав пуст: docker compose ps не показывает ни одного инстанса (стенд не поднят?)",
              file=sys.stderr)
        return 2

    rules_text = RULES_HEADER + "".join(rule(*t) for t in instances)
    for path, text in ((rules_file, rules_text), (test_file_path, test_file(instances))):
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    print(f"правила молчания: {len(instances)} инстанс(ов) -> {rules_file}, {test_file_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())