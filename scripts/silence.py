#!/usr/bin/env python3
"""Правила молчания инстанса из канонического списка (prometheus/rules/instances.yml).

Аргументы:
  1) кортежи ETCD_INSTANCES через пробел: `service|group|instance|port`
  2) путь файла, который нужно записать (по умолчанию stdout)

Зачем это вместо списка целей сбора: приложения отправляют метрики в единую точку приёма, и
сборщик опрашивает только её. Список инстансов в целях сборщика был второй копией `.env`,
которая молча разъезжалась с ним (уехавший из списка инстанс выглядел бы как «ещё не поднят»,
а добавленный в `.env` без compose — как «неизвестный»). Теперь отсутствие ряда объявляет
правило, а список инстансов остаётся в одном месте — в ETCD_INSTANCES.

Ряд, по которому судит молчание, — состояние пула: у процесса он есть всегда, независимо от того,
есть ли конфигурация. Это важно: инстанс без доли бюджета честно не обслуживает трафик (503,
готовность DOWN), но в наблюдении он обязан оставаться виден — иначе регулярное состояние флота
было бы неотличимо от упавшего процесса.

Битый кортеж пропускается с записью в stderr, как в balancers.py. Файл зафиксирован в
репозитории, чтобы сборщик поднимался даже без запуска make; расхождение с ETCD_INSTANCES ловит
`make check-silence`, а `make up` перегенерирует файл перед стартом.
"""
import sys

MARKER = "pool_config_state"

HEADER = f"""# ПРАВИЛА МОЛЧАНИЯ ИНСТАНСА. Файл генерируется: scripts/silence.py из ETCD_INSTANCES
# (`make silence-rules`), сверка — `make check-silence`. Правьте состав стенда в .env.
#
# Пока инстансы отдавали метрики по /actuator/prometheus, сборщик опрашивал каждый отдельно, и
# молчание процесса означало молчание цели. Теперь метрики идут отправкой в одну точку приёма,
# и одна цель на весь флот молчит иначе, чем молчит один инстанс: список целей такую
# неотличимость больше не выражает. Отсюда правила ниже — отсутствие ряда поимённо.
#
# Ряд состояния пула выбран потому, что существует у процесса всегда, независимо от наличия
# конфигурации: снятие конфигурации его не убирает. Поэтому инстанс без доли бюджета (503,
# готовность DOWN) молчанием не считается, а упавший процесс считается.
#
# Молчание снимается само собой: как только ряд появился, absent() перестаёт срабатывать.
#
# Окно `for` — 2м, и столько же нужно на обнаружение. Измерено на стенде (остановка контейнера
# инстанса, штатное время): от остановки до срабатывания прошло 160с. Раскладывается так — дверь
# убирает ряд из своей выдачи через metric_expiration (30с), сборщик на следующем опросе помечает
# его устаревшим, и только тогда absent() начинает видеть отсутствие; плюс окно for 2м и шаг
# проверки правил. Пятиминутное окно lookback здесь не участвует: устаревший ряд сборщик не
# переносит вперёд, а метка устаревания действует сразу. Lookback вступает в дело только если дверь
# продолжает отдавать ряд без свежих точек (например, если metric_expiration увеличить): тогда
# отсутствие заметят лишь через окно lookback, и до срабатывания пройдёт около 7 минут. Поэтому в
# наборе проверок правил нарушение задано восемьюмянутным промежутком без точек, а норма — точками
# не старше минуты.
#
# Запас берётся в сторону ложного молчания, а не ложной тревоги: молчание — не «инстанс сейчас
# упал», а «инстанса нет в наблюдении дольше, чем мы обычно ждём доставку». Промежуток на возврат
# ряда: измерено 20с от старта процесса до снятия правила (метрики приходят раз в 5с), то есть
# короткий обрыв доставки — десятки секунд — правилом молчания не ловится.

groups:
  - name: instances
    rules:
"""


def rule(service: str, group: str, instance: str) -> str:
    # Метка node в правиле обязательна: promtool считает правила одинаковыми по имени и набору
    # меток, а восемь правил молчания отличаются только выражением. Без неё check rules падает на
    # «duplicate rules», и проверка правил перестаёт быть проверкой. Значение совпадает с тем, что
    # absent() и так проставляет в метке node, — метка задана явно, чтобы правило называло инстанс
    # само по себе и переживало правку выражения.
    return f"""      - alert: InstanceSilent
        expr: absent({MARKER}{{node="{instance}"}})
        for: 2m
        labels:
          severity: warning
          node: {instance}
        annotations:
          summary: "Инстанс {{{{ $labels.node }}}} молчит в наблюдении"
          description: >-
            {service}/{group}/{instance}: нет ряда {MARKER} — процесс не присылает метрики либо
            отправка в точку приёма не доходит. Состав стенда: make check-instances.
"""


def main():
    if len(sys.argv) < 2:
        print("usage: silence.py '<tuples>' [out-file]", file=sys.stderr)
        return 1
    tuples = sys.argv[1].split()
    out_file = sys.argv[2] if len(sys.argv) > 2 else None

    rules = []
    skipped = 0
    for t in tuples:
        parts = t.split("|")
        if len(parts) != 4 or not parts[2]:
            print(f"пропущен битый кортеж: {t}", file=sys.stderr)
            skipped += 1
            continue
        rules.append(rule(parts[0], parts[1], parts[2]))

    text = HEADER + "".join(rules)
    if out_file:
        with open(out_file, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    if skipped:
        print(f"пропущено кортежей: {skipped}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
