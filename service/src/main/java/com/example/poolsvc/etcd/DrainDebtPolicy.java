package com.example.poolsvc.etcd;

/**
 * Когда инстансу публиковать неосвобождённое сжатие.
 *
 * <p>Публикация — ответ провижёру, а не настройка пула: она нужна, чтобы флот не выдал место,
 * которое сжатый инстанс ещё не отдал. Отсюда три правила, и они разные по строгости:
 *
 * <ul>
 *   <li><b>Ноль не публикуется, пока долг ненулевой и наоборот.</b> Нулевой долг означает, что
 *       место освободилось, и провижёр сможет его отдать. Пока место не освободилось, писать в
 *       etcd нечего: пустой отчёт — это шум в хранилище и лишнее событие для провижёра.
 *   <li><b>Терминальный ноль проходит всегда, без фильтров.</b> Это единственное значение, на
 *       котором держится разблокировка роста. Отфильтрованный ноль оставил бы флот
 *       недопровиженным навсегда: провижёр ждал бы освобождения, которого не увидит. Поэтому
 *       квант и ограничение частоты на ноль не распространяются.
 *   <li><b>Смена потолка публикуется всегда, даже если величина не изменилась.</b> Публикация —
 *       подтверждение текущего потолка, а не только число. Прежняя запись относится к прежнему
 *       потолку, и провижёр берёт худший случай; молчание здесь оставило бы место флота
 *       нераспределённым до какого-нибудь постороннего события, то есть практически навсегда.
 * </ul>
 *
 * <p>Квант (по умолчанию 0, то есть выключен) нужен только там, где освобождение идёт быстро и
 * каждое промежуточное значение — отдельное событие для провижёра. При нулевом кванте
 * публикуется каждое изменение величины: дренаж и так постепенный, и промежуточные значения
 * сами по себе задают темп раздачи места.
 *
 * <p>Чистая функция: ни клиента, ни потоков, ни часов — только числа, поэтому правило
 * покрывается тестами без etcd.
 */
public final class DrainDebtPolicy {

    private DrainDebtPolicy() {}

    /**
     * Значение к публикации, либо {@code null}, когда публиковать нечего.
     *
     * @param debt текущее неосвобождённое сжатие; отрицательное значение трактуется как ноль
     * @param lastPublished последнее опубликованное значение; {@code null} — публикаций ещё не было
     * @param ceilingChanged применилась ли новая конфигурация, то есть изменился потолок
     * @param quantum минимальный шаг промежуточной публикации; {@code <= 0} — не фильтровать
     * @return значение к записи в etcd либо {@code null}
     */
    public static Integer toPublish(int debt, Integer lastPublished, boolean ceilingChanged,
            int quantum) {
        // Величина неотрицательна по построению: отрицательное значение публиковать нельзя,
        // оно трактуется как «место освободилось».
        int value = Math.max(0, debt);

        if (ceilingChanged) {
            // Потолок изменился, и прежняя публикация его не подтверждает: провижёр берёт худший
            // случай и место не перераспределяет. Поэтому после любого применения значение
            // публикуется заново, даже если осталось прежним: etcd поднимет mod_revision, и
            // подтверждение текущего потолка появится. Отфильтровать здесь нельзя — флот застрял
            // бы на старой оценке навсегда.
            return value;
        }

        if (value == 0) {
            // Терминальное значение: провижёр ждёт именно его, поэтому фильтр к нему не применяется.
            // Повторную запись нуля делаем только если ноль ещё не публиковался.
            return lastPublished != null && lastPublished == 0 ? null : Integer.valueOf(0);
        }
        if (lastPublished != null && lastPublished == value) {
            // Величина не изменилась — публикация выполняется по изменению, а не по расписанию.
            return null;
        }
        if (lastPublished == null) {
            // Первая публикация ненулевого долга: её пропускать нельзя, иначе провижёр увидит
            // инстанс держащим только свой потолок и выдаст освобождаемое место другому.
            return value;
        }
        if (quantum > 0 && Math.abs((long) value - lastPublished) < quantum) {
            // Промежуточное значение мельче кванта: ждём более крупного шага. Место при этом
            // остаётся незанятым, что безопаснее выдачи его преждевременно.
            return null;
        }
        return value;
    }
}
